import AppKit
import Observation

@MainActor
@Observable
final class ClipboardMonitor {
    enum Status: Equatable {
        case monitoring, paused, accessDenied, unavailable, tooLarge, partial

        var message: String? {
            switch self {
            case .monitoring: nil
            case .paused: "Monitoring paused"
            case .accessDenied: "Clipboard access is blocked. Allow Klip in System Settings, then copy again."
            case .unavailable: "Couldn’t read this copy. Check clipboard access in System Settings, then copy again."
            case .tooLarge: "This copy exceeds the 64 MB clipboard limit."
            case .partial: "Some source formats couldn’t be saved. Available formats are kept; a source-app-dependent paste may not work later."
            }
        }
    }

    // Search/preview text is bounded independently of the original clipboard bytes.
    static let maximumTextBytes = 2 * 1024 * 1024
    static let maximumPayloadBytes = 64 * 1024 * 1024
    static let maximumItems = 1024
    static let maximumTypesPerItem = 128
    private static let sensitiveTypes: Set<NSPasteboard.PasteboardType> = Set([
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "de.petermaurer.TransientPasteboardType",
        "com.agilebits.onepassword"
    ].map { NSPasteboard.PasteboardType($0) })

    private let pasteboard: NSPasteboard
    private let writer: ClipboardWriter
    let privacy: PrivacyPolicy
    private let sourceApplication: () -> String?
    private let accessBehavior: () -> NSPasteboard.AccessBehavior
    private let readString: ((NSPasteboard.PasteboardType) -> String?)?
    private let readData: (NSPasteboardItem, NSPasteboard.PasteboardType) -> Data?
    private let onCapture: (ClipboardSnapshot) -> Void
    private var lastSeenChangeCount: Int
    private var timer: Timer?
    private(set) var status: Status = .monitoring

    init(pasteboard: NSPasteboard = .general, writer: ClipboardWriter,
         privacy: PrivacyPolicy,
         sourceApplication: @escaping () -> String? = { NSWorkspace.shared.frontmostApplication?.bundleIdentifier },
         accessBehavior: (() -> NSPasteboard.AccessBehavior)? = nil,
         readString: ((NSPasteboard.PasteboardType) -> String?)? = nil,
         readData: ((NSPasteboardItem, NSPasteboard.PasteboardType) -> Data?)? = nil,
         onCapture: @escaping (ClipboardSnapshot) -> Void) {
        self.pasteboard = pasteboard
        self.writer = writer
        self.privacy = privacy
        self.sourceApplication = sourceApplication
        self.accessBehavior = accessBehavior ?? { pasteboard.accessBehavior }
        self.readString = readString
        self.readData = readData ?? { $0.data(forType: $1) }
        self.onCapture = onCapture
        lastSeenChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        rebaseline()
        let timer = Timer(timeInterval: 0.05, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.005
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func rebaseline() {
        lastSeenChangeCount = pasteboard.changeCount
        status = privacy.isPaused ? .paused : .monitoring
    }

    func poll() {
        let changeCount = pasteboard.changeCount
        if privacy.isPaused {
            lastSeenChangeCount = changeCount
            status = .paused
            return
        }
        if accessBehavior() == .alwaysDeny {
            lastSeenChangeCount = changeCount
            status = .accessDenied
            return
        }
        if status == .paused || status == .accessDenied { status = .monitoring }
        guard changeCount != lastSeenChangeCount else { return }
        lastSeenChangeCount = changeCount
        status = .monitoring
        let source = sourceApplication()
        guard privacy.allowsCapture(from: source),
              writer.lastWrittenChangeCount != changeCount else { return }
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.sensitiveTypes), !types.contains(ClipboardWriter.internalType) else { return }
        guard let sourceItems = pasteboard.pasteboardItems, !sourceItems.isEmpty else { return }
        guard sourceItems.count <= Self.maximumItems,
              sourceItems.allSatisfy({ $0.types.count <= Self.maximumTypesPerItem }) else { status = .tooLarge; return }
        // Check every item's markers before reading any payload.
        guard sourceItems.allSatisfy({ Set($0.types).isDisjoint(with: Self.sensitiveTypes) && !$0.types.contains(ClipboardWriter.internalType) }) else { return }
        if let readString, let first = sourceItems.first,
           let type = first.types.contains(.string) ? NSPasteboard.PasteboardType.string : first.types.contains(.URL) ? .URL : nil {
            guard readString(type) != nil else { status = .unavailable; return }
            guard pasteboard.changeCount == changeCount else { return }
        }
        // Reading native URLs also lets AppKit deliver the sandbox access attached
        // to a file copy, rather than relying only on a decoded URL string.
        let grantedURLs: [URL] = types.contains(.fileURL)
            ? (pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []) : []
        guard pasteboard.changeCount == changeCount else { return }
        var captured: [ClipboardPayloadItem] = []
        var unavailable: [String] = []
        var byteCount = 0
        for item in sourceItems {
            var representations: [ClipboardRepresentation] = []
            for type in item.types {
                guard type.rawValue.utf8.count <= 512 else { status = .tooLarge; return }
                if let data = readData(item, type) {
                    byteCount += data.count + type.rawValue.utf8.count
                    guard byteCount <= Self.maximumPayloadBytes else { status = .tooLarge; return }
                    representations.append(ClipboardRepresentation(type: type.rawValue, data: data))
                } else { unavailable.append(type.rawValue) }
                guard pasteboard.changeCount == changeCount else { return }
            }
            var files: [ClipboardFileReference] = []
            if let data = representations.first(where: { $0.type == NSPasteboard.PasteboardType.fileURL.rawValue })?.data,
               let string = String(data: data, encoding: .utf8), let url = URL(string: string), url.isFileURL {
                files = [ClipboardFileReference.capture(grantedURLs.first(where: { $0.standardizedFileURL.path == url.standardizedFileURL.path }) ?? url)]
            } else if let data = representations.first(where: { $0.type == "NSFilenamesPboardType" })?.data,
                      let paths = (try? PropertyListSerialization.propertyList(from: data, format: nil)) as? [String] {
                guard paths.count <= Self.maximumItems else { status = .tooLarge; return }
                files = paths.map { ClipboardFileReference.capture(URL(fileURLWithPath: $0)) }
            }
            byteCount += files.reduce(0) { $0 + $1.originalURL.utf8.count + ($1.bookmark?.count ?? 0) }
            guard byteCount <= Self.maximumPayloadBytes else { status = .tooLarge; return }
            captured.append(ClipboardPayloadItem(representations: representations, files: files))
        }
        guard pasteboard.changeCount == changeCount else { return }
        guard captured.contains(where: { !$0.representations.isEmpty }) else { status = .unavailable; return }
        let (content, kind) = ClipboardPayloadSummary.describe(captured)
        guard pasteboard.changeCount == changeCount else { return }
        let snapshot = ClipboardSnapshot(content: content, kind: kind, changeCount: changeCount,
            capturedAt: Date(), sourceApplicationID: source, items: captured, unavailableTypes: unavailable)
        guard snapshot.byteCount <= Self.maximumPayloadBytes else { status = .tooLarge; return }
        status = unavailable.isEmpty ? .monitoring : .partial
        onCapture(snapshot)
    }
}
