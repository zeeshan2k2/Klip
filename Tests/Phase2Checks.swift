import AppKit
import Carbon
import Darwin
import SwiftUI

/// Uses a named pasteboard only. Never reads or changes the user's general clipboard.
@main
struct Phase2Checks {
    @MainActor
    static func main() {
        setbuf(stdout, nil)
        let app = NSApplication.shared
        app.setActivationPolicy(.accessory)
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }
        func externalCopy(_ text: String, type: NSPasteboard.PasteboardType = .string) {
            pasteboard.clearContents()
            pasteboard.setString(text, forType: type)
        }
        func snapshot(_ text: String) -> ClipboardSnapshot {
            ClipboardSnapshot(content: text, kind: ContentClassifier().classify(text),
                              changeCount: pasteboard.changeCount, capturedAt: Date(), sourceApplicationID: "test.source")
        }

        externalCopy("pre-launch contents")
        let store = ClipboardHistoryStore()
        let privacy = PrivacyPolicy()
        let writer = ClipboardWriter(pasteboard: pasteboard)
        var source = "test.source"
        var access = NSPasteboard.AccessBehavior.alwaysAllow
        var reads = 0
        var failRead = false
        var changeDuringRead = false
        let monitor = ClipboardMonitor(pasteboard: pasteboard, writer: writer, privacy: privacy,
                                       sourceApplication: { source }, accessBehavior: { access }, readString: { type in
            reads += 1
            let value = pasteboard.string(forType: type)
            if changeDuringRead {
                changeDuringRead = false
                externalCopy("newest generation")
            }
            return failRead ? nil : value
        }, onCapture: { store.record($0) })
        monitor.poll()
        assert(store.items.isEmpty && reads == 0, "Do not import the clipboard present before monitoring")
        externalCopy("alpha")
        monitor.poll()
        assert(store.items.map(\.content) == ["alpha"])
        assert(pasteboard.string(forType: .string) == "alpha", "Observation must not alter the clipboard")
        externalCopy("alpha")
        monitor.poll()
        assert(store.items.count == 1, "Consecutive duplicates must collapse")
        externalCopy("beta")
        monitor.poll()
        externalCopy("alpha")
        monitor.poll()
        assert(store.items.map(\.content) == ["alpha", "beta", "alpha"], "Nonconsecutive copies are distinct")
        print("PASS: startup baseline, nonmutating capture, ordering, and consecutive deduplication")

        let exact = "  Line one\nLine two\t👋 مرحبا\n"
        externalCopy(exact)
        monitor.poll()
        let count = store.items.count
        assert(writer.write(store.items[0].snapshot))
        assert(pasteboard.string(forType: .string) == exact)
        monitor.poll()
        assert(store.items.count == count, "Own writes must not become history entries")
        externalCopy("https://example.com/path?x=1", type: .URL)
        monitor.poll()
        assert(store.items[0].kind == .link)
        assert(writer.write(store.items[0].snapshot))
        assert(pasteboard.string(forType: .URL) == "https://example.com/path?x=1")
        monitor.poll()
        print("PASS: exact Unicode/whitespace copy-back, URL-only pasteboards, and self-write suppression")

        var before = reads
        privacy.isPaused = true
        externalCopy("paused contents")
        monitor.poll()
        assert(reads == before && monitor.status == .paused)
        privacy.isPaused = false
        monitor.rebaseline()
        monitor.poll()
        assert(reads == before, "Resume must not import a copy made while paused")
        privacy.excludedApplicationIDs.insert("test.excluded")
        source = "test.excluded"
        externalCopy("excluded contents")
        monitor.poll()
        assert(reads == before)
        source = "test.source"
        access = .alwaysDeny
        externalCopy("permission denied")
        monitor.poll()
        assert(reads == before && monitor.status == .accessDenied)
        access = .alwaysAllow
        monitor.poll()
        assert(reads == before, "Permission recovery must not import previously blocked data")
        for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.klip.internal-write"] {
            let item = NSPasteboardItem()
            item.setString("private contents", forType: .string)
            item.setString("1", forType: NSPasteboard.PasteboardType(type))
            pasteboard.clearContents()
            pasteboard.writeObjects([item])
            monitor.poll()
            assert(reads == before)
        }
        print("PASS: pause/resume, exclusions, denied access, sensitive markers skip payload reads")

        externalCopy("unavailable contents")
        failRead = true
        monitor.poll()
        assert(monitor.status == .unavailable)
        failRead = false
        before = store.items.count
        externalCopy("outdated generation")
        changeDuringRead = true
        monitor.poll()
        assert(store.items.count == before, "A changing pasteboard must not produce a mismatched capture")
        monitor.poll()
        assert(store.items[0].content == "newest generation")
        let beyondPreview = String(repeating: "x", count: ClipboardMonitor.maximumTextBytes + 1)
        externalCopy(beyondPreview)
        monitor.poll()
        assert(monitor.status == .monitoring)
        assert(store.items[0].content.utf8.count <= ClipboardMonitor.maximumTextBytes)
        assert(writer.write(store.items[0].snapshot))
        assert(pasteboard.string(forType: .string) == beyondPreview, "A bounded preview must not truncate copy-back")
        monitor.poll()
        let largeText = String(repeating: "y", count: 1024 * 1024)
        externalCopy(largeText)
        monitor.poll()
        assert(store.items[0].content == largeText && monitor.status == .monitoring)
        print("PASS: unavailable reads, clipboard-generation races, latest-copy recovery, and text size limits")

        let classifier = ContentClassifier()
        assert(classifier.classify("https://example.com/a?b=1") == .link)
        for text in ["example.com", "hello", "javascript:alert(1)", "https://example.com has text", "https://", " https://example.com"] {
            assert(classifier.classify(text) == .text)
        }
        let bounded = ClipboardHistoryStore(capacity: 3, byteLimit: 10)
        bounded.record(snapshot("aaaa"))
        bounded.record(snapshot("bbbb"))
        bounded.record(snapshot("cccc"))
        assert(bounded.items.map(\.content) == ["cccc", "bbbb"])
        let limited = ClipboardHistoryStore(capacity: 3)
        for text in ["one", "two", "three", "four"] { limited.record(snapshot(text)) }
        assert(limited.items.map(\.content) == ["four", "three", "two"])
        let model = HistoryViewModel(store: limited, privacy: privacy)
        model.query = "THREE"
        assert(model.selectedItem?.content == "three")
        var copied: String?
        model.onCopy = { copied = $0.content }
        model.copySelection()
        assert(copied == "three")
        model.query = "no matching content"
        assert(model.filteredItems.isEmpty && model.selectedID == nil)
        model.query = ""
        model.moveSelection(by: 500)
        assert(model.selectedItem?.content == "two")
        model.remove(model.selectedItem!)
        assert(model.selectedItem?.content == "three")
        model.clearHistory()
        assert(limited.items.isEmpty && model.selectedID == nil)
        assert(ClipboardHistoryStore().items.isEmpty, "A fresh process/store has no history to restore")
        print("PASS: conservative URL classification, count/byte bounds, filtered copy, deletion, clear, and fresh-store state")

        // Exercise the real panel against the named pasteboard, never the general one.
        let uiStore = ClipboardHistoryStore(items: HistoryItem.examples)
        let uiModel = HistoryViewModel(store: uiStore)
        let frameName = "Klip.Phase2.Checks.\(UUID().uuidString)"
        let panel = HistoryPanelController(model: uiModel, frameAutosaveName: frameName)
        defer {
            panel.dismiss()
            panel.window?.setFrameAutosaveName("")
            UserDefaults.standard.removeObject(forKey: "NSWindow Frame \(frameName)")
        }
        var copyCount = 0
        uiModel.onCopy = { item in
            copyCount += 1
            assert(writer.write(item.snapshot))
            panel.dismiss()
        }
        func openPanel() {
            uiModel.query = ""
            uiModel.selectedID = uiStore.items.first?.id
            panel.showWindow(nil)
            panel.window!.makeKeyAndOrderFront(nil)
            app.activate(ignoringOtherApps: true)
            RunLoop.main.run(until: Date().addingTimeInterval(0.15))
        }
        func key(_ text: String, code: UInt16, modifiers: NSEvent.ModifierFlags = []) {
            let event = NSEvent.keyEvent(with: .keyDown, location: .zero, modifierFlags: modifiers, timestamp: ProcessInfo.processInfo.systemUptime,
                                         windowNumber: panel.window!.windowNumber, context: nil, characters: text, charactersIgnoringModifiers: text,
                                         isARepeat: false, keyCode: code)!
            app.sendEvent(event)
            RunLoop.main.run(until: Date().addingTimeInterval(0.08))
        }
        openPanel()
        key("2", code: 19)
        assert(uiModel.query == "2" && copyCount == 0, "Ordinary numbers should type into search")
        uiModel.query = ""
        key("2", code: 19, modifiers: .command)
        assert(copyCount == 1 && !panel.window!.isVisible)
        assert(pasteboard.string(forType: .string) == uiStore.items[1].content)
        openPanel()
        key("\r", code: 36)
        assert(copyCount == 2 && !panel.window!.isVisible, "Return copies and dismisses")
        openPanel()
        panel.window!.setContentSize(NSSize(width: 480, height: 520))
        RunLoop.main.run(until: Date().addingTimeInterval(0.1))
        let position = NSPoint(x: 80, y: panel.window!.contentView!.bounds.height - 135)
        for clickCount in [1, 2] {
            for type in [NSEvent.EventType.leftMouseDown, .leftMouseUp] {
                let event = NSEvent.mouseEvent(with: type, location: position, modifierFlags: [], timestamp: ProcessInfo.processInfo.systemUptime,
                                              windowNumber: panel.window!.windowNumber, context: nil, eventNumber: 1, clickCount: clickCount, pressure: 1)!
                app.sendEvent(event)
                RunLoop.main.run(until: Date().addingTimeInterval(0.02))
            }
        }
        RunLoop.main.run(until: Date().addingTimeInterval(0.15))
        assert(uiModel.inspectedItem?.id == uiStore.items[0].id && copyCount == 2, "Double-click previews without copying")
        key("\u{1B}", code: 53)
        assert(!panel.window!.isVisible && uiModel.inspectedItem == nil)
        openPanel()
        assert(panel.window!.contentView!.bounds.size == NSSize(width: 480, height: 520))
        key("\u{1B}", code: 53)
        print("PASS: typing in search, ⌘2 copy-back, Return copy-back, double-click preview, Escape, and retained resize")

        monitor.start()
        externalCopy("timer-driven capture")
        RunLoop.main.run(until: Date().addingTimeInterval(0.20))
        assert(store.items.first?.content == "timer-driven capture")
        monitor.stop()
        before = reads
        externalCopy("after monitoring stops")
        RunLoop.main.run(until: Date().addingTimeInterval(0.5))
        assert(reads == before)
        print("PASS: scheduled monitoring and stopping the timer")

        var invocations = 0
        let hotKey = HistoryHotKey { invocations += 1 }
        if hotKey.register() {
            var event: EventRef?
            assert(CreateEvent(nil, OSType(kEventClassKeyboard), UInt32(kEventHotKeyPressed), GetCurrentEventTime(), 0, &event) == noErr)
            var identifier = EventHotKeyID(signature: 0x4B4C4950, id: 1)
            assert(SetEventParameter(event, EventParamName(kEventParamDirectObject), EventParamType(typeEventHotKeyID),
                                     MemoryLayout<EventHotKeyID>.size, &identifier) == noErr)
            assert(SendEventToEventTarget(event, GetApplicationEventTarget()) == noErr)
            if let event { ReleaseEvent(event) }
            assert(invocations == 1)
            hotKey.stop()
            var occupied: EventHotKeyRef?
            let reserved = RegisterEventHotKey(UInt32(kVK_ANSI_V), UInt32(cmdKey | shiftKey), EventHotKeyID(signature: 0x54455354, id: 2),
                                              GetApplicationEventTarget(), UInt32(kEventHotKeyExclusive), &occupied)
            if reserved == noErr {
                assert(!hotKey.register(), "An occupied global shortcut must report failure")
                if let occupied { UnregisterEventHotKey(occupied) }
            }
            assert(hotKey.register())
            hotKey.stop()
            print("PASS: system hotkey registration, event dispatch, conflict handling, and cleanup")
        } else {
            print("SKIP: ⌘⇧V is already reserved by another running app; verify opening from the menu bar")
        }
        print("All Phase 2 checks passed. No general clipboard access was used.")
    }
}
